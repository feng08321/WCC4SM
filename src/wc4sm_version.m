function version = wc4sm_version()
%WC4SM_VERSION Single source of truth for the WCC4SM application version.
%   VERSION = WC4SM_VERSION() returns the display version string (e.g. 'V1.1')
%   used in window titles, the header label, and the About/HELP dialog.
%   Update this one function when cutting a new release. File names
%   (WCC4SM_V1_0.m) and the Session format identifier stay unchanged across
%   releases.

    version = 'V1.2';
end
